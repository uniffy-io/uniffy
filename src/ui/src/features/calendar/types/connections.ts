export type CalendarProviderId = "google" | "microsoft";

/** `inbound` keeps the calendar read-only in Uniffy; `two_way` sends edits back to the provider. */
export type CalendarSyncDirection = "inbound" | "two_way";

export type ConnectedCalendarState =
  | "pending"
  | "healthy"
  | "failing"
  | "broken"
  | "paused"
  | "reauth_required"
  | "detached";

export type CalendarSyncError =
  | "unreachable"
  | "rate_limited"
  | "provider_error"
  | "permission_denied"
  | "not_found"
  | "reauth_required"
  | "unprocessable";

export type CalendarConnectionStatus = "active" | "paused" | "reauth_required" | "disconnected";

export type ProviderCalendarAccess = "owner" | "writer" | "reader" | "free_busy";

export type ProviderCredentialSource = "none" | "organization" | "deployment";

export type ProviderSyncAudience = "off" | "admins" | "everyone";

export type ParticipantResponse = "accepted" | "tentative" | "declined" | "pending";

/** The provider calendar behind a connected Uniffy calendar; present for its owner only. */
export interface ConnectedCalendarSummary {
  connectedCalendarId: string;
  connectionId: string;
  /** Null when the server names a provider this client does not know. */
  provider: CalendarProviderId | null;
  accountEmail: string;
  direction: CalendarSyncDirection;
  state: ConnectedCalendarState;
  lastError?: CalendarSyncError;
  lastSuccessAt?: string;
  countsAsBusy: boolean;
}

export interface ProviderCalendarInfo {
  id: string;
  name: string;
  /** Hex; shown until a Uniffy calendar exists. */
  providerColor: string;
  access?: ProviderCalendarAccess;
  isPrimary: boolean;
  /** Generated by the provider, such as holidays. */
  isSystem: boolean;
  syncEnabled: boolean;
  direction: CalendarSyncDirection;
  /** The account may write and the deployment and organization allow two-way sync. */
  canWrite: boolean;
  countsAsBusy: boolean;
  calendarId?: string;
  state: ConnectedCalendarState;
  lastError?: CalendarSyncError;
  lastSuccessAt?: string;
  eventCount: number;
  skippedCount: number;
}

export interface CalendarConnectionInfo {
  id: string;
  provider: CalendarProviderId | null;
  accountEmail: string;
  status: CalendarConnectionStatus;
  calendars: ProviderCalendarInfo[];
  lastSyncedAt?: string;
  createdAt: string;
}

export interface ProviderAvailabilityInfo {
  provider: CalendarProviderId;
  configured: boolean;
  credentialSource: ProviderCredentialSource;
  writesEnabled: boolean;
}

export interface ProviderAppSettingsInfo {
  provider: CalendarProviderId;
  source: ProviderCredentialSource;
  /** Set only when the organization supplies its own app. */
  clientId: string;
  /** The last characters of the stored secret; the secret itself never leaves the server. */
  clientSecretHint: string;
  /** Microsoft only. */
  tenant: string;
  deploymentConfigured: boolean;
}

export interface ProviderSettingsInfo {
  providers: ProviderAppSettingsInfo[];
  redirectUri: string;
}

/** Someone a provider lists on an event; people outside the organization appear only here. */
export interface EventParticipant {
  email: string;
  displayName: string;
  response: ParticipantResponse;
  isOrganizer: boolean;
  isOptional: boolean;
  /** Set when the address belongs to a member of the organization. */
  userId?: string;
}
