// Helper to find a channel by ID
export function getMockChannel(channelId: string): ChatChannel | undefined {
  return MOCK_CHANNELS.find(ch => ch.id === channelId);
}

// Helper to get channels the current user belongs to
export function getChannelsForUser(userId: string, members: Record<string, { userId: string }[]>): ChatChannel[] {
  return MOCK_CHANNELS.filter(ch => {
    const channelMembers = members[ch.id];
    return channelMembers?.some(m => m.userId === userId);
  });
}
