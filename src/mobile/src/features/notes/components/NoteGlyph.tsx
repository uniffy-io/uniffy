/**
 * A note's icon as the web draws it: its emoji, its picked Phosphor icon, the canvas mark for a
 * canvas, and a plain document otherwise.
 */
export function NoteGlyph({
  icon,
  isCanvas = false,
  size,
  color,
}: {
  icon?: { type: string; value: string } | null;
  isCanvas?: boolean;
  size: number;
  color: string;
}) {
  if (isCanvas) return <SelectionAll size={size} color={color} weight="duotone" />;
  if (icon?.value && icon.type === "emoji") {
    return <Text style={{ fontSize: size - 2 }}>{icon.value}</Text>;
  }
  const Named =
    icon?.value && Object.hasOwn(NOTE_ICONS, icon.value) ? NOTE_ICONS[icon.value] : FileText;
  return <Named size={size} color={color} />;
}
